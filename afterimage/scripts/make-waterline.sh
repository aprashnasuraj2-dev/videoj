#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLAN="$ROOT/media-plan.json"
OUT="$ROOT/public/media"
WORK="$ROOT/.waterline-work"
mkdir -p "$OUT" "$WORK"

DRY_URL="$(node -e "const p=require(process.argv[1]); process.stdout.write(p.sources.dry.url)" "$PLAN")"
WET_URL="$(node -e "const p=require(process.argv[1]); process.stdout.write(p.sources.wet.url)" "$PLAN")"

curl --fail --location --retry 3 --output "$WORK/dry.png" "$DRY_URL"
curl --fail --location --retry 3 --output "$WORK/wet.png" "$WET_URL"

ffmpeg -nostdin -loglevel error -y \
  -loop 1 -framerate 24 -t 18 -i "$WORK/dry.png" \
  -loop 1 -framerate 24 -t 18 -i "$WORK/wet.png" \
  -f lavfi -t 18 -i "anoisesrc=color=brown:amplitude=0.025:sample_rate=48000" \
  -f lavfi -t 18 -i "sine=frequency=58:sample_rate=48000" \
  -filter_complex "[0:v]scale=1280:720:force_original_aspect_ratio=increase,crop=1280:720,setsar=1[d];[1:v]scale=1280:720:force_original_aspect_ratio=increase,crop=1280:720,setsar=1[w];[d][w]xfade=transition=fade:duration=2:offset=6,trim=duration=18,eq=contrast=1.03:saturation=0.92:brightness=-0.01,noise=alls=1.4:allf=t+u,format=yuv420p[v];[2:a]highpass=f=60,lowpass=f=1200,volume=0.28[n];[3:a]volume=0.045[s];[n][s]amix=inputs=2:normalize=0,afade=t=in:st=0:d=1.2,afade=t=out:st=16.2:d=1.8[a]" \
  -map "[v]" -map "[a]" -r 24 -t 18 \
  -c:v libx264 -preset medium -crf 22 -pix_fmt yuv420p \
  -c:a aac -b:a 96k -movflags +faststart \
  "$OUT/the-waterline-v1.mp4"

ffmpeg -nostdin -loglevel error -y -ss 5 -i "$OUT/the-waterline-v1.mp4" -frames:v 1 -q:v 2 "$OUT/the-waterline-v1-poster.jpg"
for t in 3 5 7 11 13 15; do
  ffmpeg -nostdin -loglevel error -y -ss "$t" -i "$OUT/the-waterline-v1.mp4" -frames:v 1 -q:v 3 "$OUT/frame-${t}.jpg"
done

cat > "$OUT/the-waterline-v1.vtt" <<'EOF'
WEBVTT

00:00.000 --> 00:06.000
[Dry spillway. A closed copper gate faces the empty floor.]

00:06.000 --> 00:10.000
[First flow crosses the floor. Stone darkens and reflections appear.]

00:10.000 --> 00:18.000
[Shallow water settles beneath the same locked architecture.]
EOF

cat > "$OUT/the-waterline-v1-chapters.vtt" <<'EOF'
WEBVTT

00:00.000 --> 00:06.000
Dry

00:06.000 --> 00:10.000
First flow

00:10.000 --> 00:18.000
Waterline
EOF

node - "$OUT" <<'NODE'
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const { readFileSync, writeFileSync, statSync } = require('node:fs');
const { join } = require('node:path');
const out = process.argv[2];
const video = join(out, 'the-waterline-v1.mp4');
const probe = JSON.parse(execFileSync('ffprobe', [
  '-v','error','-show_entries','format=duration,size,bit_rate:stream=index,codec_name,codec_type,width,height,r_frame_rate',
  '-of','json',video
], { encoding:'utf8' }));
const hash = file => createHash('sha256').update(readFileSync(join(out,file))).digest('hex');
const manifest = {
  id:'the-waterline-v1',
  generatedAt:new Date().toISOString(),
  pair:{pinnedSeconds:5,currentSeconds:13},
  runtimeSeconds:Number(probe.format.duration),
  sizeBytes:Number(probe.format.size),
  bitRate:Number(probe.format.bit_rate),
  streams:probe.streams,
  files:{
    video:{name:'the-waterline-v1.mp4',sha256:hash('the-waterline-v1.mp4'),bytes:statSync(video).size},
    poster:{name:'the-waterline-v1-poster.jpg',sha256:hash('the-waterline-v1-poster.jpg')},
    captions:{name:'the-waterline-v1.vtt',sha256:hash('the-waterline-v1.vtt')},
    chapters:{name:'the-waterline-v1-chapters.vtt',sha256:hash('the-waterline-v1-chapters.vtt')}
  },
  sound:'Procedural brown-noise water bed plus 58 Hz low sine, generated by FFmpeg lavfi; no third-party recording.',
  sourceFrames:'Two original AI-assisted matched architectural keyframes; source task IDs are recorded in ../../media-plan.json.',
  intendedUse:'AFTERIMAGE locked-camera dry to first-flow comparison.'
};
writeFileSync(join(out,'the-waterline-v1.json'), JSON.stringify(manifest,null,2)+'\n');
NODE

cp "$WORK/dry.png" "$OUT/waterline-dry.png"
cp "$WORK/wet.png" "$OUT/waterline-wet.png"
